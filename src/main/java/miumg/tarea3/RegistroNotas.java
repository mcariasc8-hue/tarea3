    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        // TODO add your handling code here:
        if (Indice <6){
            double valor = Double.parseDouble(txtNota.getText());
            Notas[Indice]= valor;
            Indice++;
            txtNota.setText("");
            JOptionPane.showMessageDialog(null,"Nota Guardada (" +Indice +"/6)");
        } else{
            JOptionPane.showMessageDialog(null,"Ya ingresó las 6 notas");
        } 
    }//GEN-LAST:event_btnAgregarActionPerformed

    private void btnGenerarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGenerarActionPerformed
        // TODO add your handling code here:
        int Aprobados = 0, Reprobados = 0;
        double suma = 0;
        
        for (int i = 0; i < 6; i++){
            suma += Notas [i];
            if (Notas [i]>=61){
                Aprobados++;
            } else{
                Reprobados++;
            }
            
        }
        double Promedio = suma / 6;
        
        try {
            FileWriter fw = new
        FileWriter("monica_reporte_notas.txt");
            PrintWriter pw = new
        PrintWriter (fw);
            pw.println("Reporte de Notas");
            pw.println("Aprobados:" + Aprobados);
            pw.println("Reprobados:" + Reprobados);
            pw.println("Promedio de Notas:" + Promedio);
            pw.close();
            JOptionPane.showMessageDialog(null,"Reporte generado con éxito");
        } catch (Exception e){
            JOptionPane.showMessageDialog(null,"Error al crear el archivo" );
        }
    }//GEN-LAST:event_btnGenerarActionPerformed

