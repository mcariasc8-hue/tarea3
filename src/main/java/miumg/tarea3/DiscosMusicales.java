        private void cargarArchivo() {
        try {
            File archivo = new File("discos.csv");
            Scanner lector = new Scanner(archivo);
            cantidad = 0;
            while (lector.hasNextLine() && cantidad < 5) {
                String linea = lector.nextLine();
                String[] partes = linea.split(",");
                titulos[cantidad] = partes[0].trim();
                anios[cantidad] = Integer.parseInt(partes[1].trim());
                cantidad++;
            }
            lector.close();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error: No se encontró el archivo discos.csv");
        }
    }

